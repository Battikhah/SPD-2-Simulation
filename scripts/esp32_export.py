"""Stage 2 (TensorFlow venv, CPU): port each fold model to Keras, check float parity, convert to full-int8
TFLite, and score every held-out fold with the int8 interpreter, so metrics reflect device arithmetic.

Also reports per candidate: int8 .tflite size, operator list vs the TFLM builtin set, a tensor-lifetime
arena lower bound, and writes a C array + int8 input fixture for the ESP-IDF benchmark harness.
Metrics use cross-fitted thresholds (chosen on the other four folds): F2-optimal and a precision floor.
Development data only; the test partition is never read. Run: outputs/tf-venv/Scripts/python.exe
scripts/esp32_export.py [--smoke]
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.model_selection import GroupKFold

sys.path.insert(0, str(Path(__file__).resolve().parent))
from esp32_arch import CANDIDATES, keras_model  # noqa: E402
from esp32_train import dev_frame, run_root, units  # noqa: E402

TFLM_OPS = {"CONV_2D", "DEPTHWISE_CONV_2D", "MAX_POOL_2D", "MEAN", "FULLY_CONNECTED", "ADD", "LOGISTIC", "PAD",
            "MUL", "RESHAPE", "QUANTIZE", "DEQUANTIZE", "AVERAGE_POOL_2D", "SUB"}
PRECISION_FLOOR = 0.90


def to_int8(model, rep):
    import tensorflow as tf

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = lambda: ([r[None, ..., None].astype(np.float32)] for r in rep)
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = conv.inference_output_type = tf.int8
    return conv.convert()


def interpreter(blob):
    """Reference int8 kernels: no XNNPACK delegate (it crashes on Windows after resizes), and closer to
    the TFLM reference arithmetic than optimised CPU kernels."""
    import tensorflow as tf

    return tf.lite.Interpreter(model_content=blob,
                               experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)


def run_int8(blob, X, batch=256):

    it = interpreter(blob)
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    (si, zi), (so, zo) = i["quantization"], o["quantization"]
    out = []
    for start in range(0, len(X), batch):
        xb = X[start:start + batch]
        it.resize_tensor_input(i["index"], [len(xb), *X.shape[1:], 1])
        it.allocate_tensors()
        q = np.clip(np.round(xb / si + zi), -128, 127).astype(np.int8)[..., None]
        it.set_tensor(i["index"], q)
        it.invoke()
        out.append((it.get_tensor(o["index"]).astype(np.float32).ravel() - zo) * so)
    return np.concatenate(out)


def inspect(blob):
    """Operator names and a tensor-lifetime arena lower bound (no planner overhead or alignment)."""

    it = interpreter(blob)
    it.allocate_tensors()
    ops = it._get_ops_details()  # noqa: SLF001
    tensors = {t["index"]: t for t in it.get_tensor_details()}
    # Constants (weights/biases) are never written by an op and are not the model input; TFLM keeps
    # them in flash, so only activations count toward the arena.
    written = {t for op in ops for t in op["outputs"]}
    inputs = {d["index"] for d in it.get_input_details()}
    const = {t for t in tensors if t not in written and t not in inputs}
    first, last = {}, {}
    for j, op in enumerate(ops):
        for t in list(op["inputs"]) + list(op["outputs"]):
            if t < 0 or t in const:
                continue
            first.setdefault(t, j)
            last[t] = j
    size = {t: int(np.prod(tensors[t]["shape"])) * np.dtype(tensors[t]["dtype"]).itemsize for t in first}
    peak = max(sum(size[t] for t in first if first[t] <= j <= last[t]) for j in range(len(ops)))
    return sorted({op["op_name"] for op in ops}), peak


def c_array(blob, name):
    body = ",".join(f"0x{b:02x}" for b in blob)
    return (f"// Generated by scripts/esp32_export.py; do not edit.\n#include <cstdint>\n"
            f"alignas(16) const unsigned char {name}[] = {{{body}}};\nconst unsigned int {name}_len = {len(blob)};\n")


def _fbeta(prec, rec, beta):
    return (1 + beta**2) * prec * rec / np.maximum(beta**2 * prec + rec, 1e-12)


# Each rule scores every candidate threshold on the *other* folds; the best threshold (ties: the
# highest, i.e. fewest alarms) is then applied unchanged to the held-out fold.
RULES = {
    "f2": lambda prec, rec, fpr: _fbeta(prec, rec, 2.0),
    "f1": lambda prec, rec, fpr: _fbeta(prec, rec, 1.0),
    "f0.5": lambda prec, rec, fpr: _fbeta(prec, rec, 0.5),
    "fpr10": lambda prec, rec, fpr: np.where(fpr <= 0.10, rec, -1.0),
    "precision_floor": lambda prec, rec, fpr: np.where(prec >= PRECISION_FLOOR, rec, -1.0),
}


def choose_threshold(y, s, rule):
    order = np.argsort(-s, kind="mergesort")
    ss, ys = s[order], y[order]
    last = np.r_[ss[1:] != ss[:-1], True]  # last position of each distinct score
    tp, fp, thr = np.cumsum(ys)[last], np.cumsum(1 - ys)[last], ss[last]
    rec, prec, fpr = tp / max(ys.sum(), 1), tp / np.maximum(tp + fp, 1), fp / max((1 - ys).sum(), 1)
    return thr[int(np.argmax(RULES[rule](prec, rec, fpr)))]


def crossfit(y, s, folds, rules=RULES):
    """Cross-fitted operating points: per held-out fold, threshold chosen on the other folds only."""
    res = {}
    for rule in rules:
        pred = np.zeros(len(y), bool)
        for tr, te in folds:
            pred[te] = s[te] >= choose_threshold(y[tr], s[tr], rule)
        tp, fp = int((pred & (y == 1)).sum()), int((pred & (y == 0)).sum())
        rec, prec = tp / (y == 1).sum(), tp / max(tp + fp, 1)
        res |= {f"{rule}_recall": rec, f"{rule}_precision": prec, f"{rule}_fpr": fp / (y == 0).sum(),
                f"{rule}_f1": 2 * prec * rec / max(prec + rec, 1e-12), f"{rule}_tp": tp, f"{rule}_fp": fp}
    return res


def metric_rows(oof8, oof_float, y, folds):
    rows = []
    for name in sorted({c.split("|")[0] for c in oof8.columns if "|" in c}):
        cols = [c for c in oof8.columns if c.startswith(name + "|seed")]
        if len(cols) > 1:
            oof8[f"{name}|ensemble"] = oof8[cols].mean(1)
            oof_float[f"{name}|ensemble"] = oof_float[cols].mean(1)
        for col in [c for c in oof8.columns if c.startswith(name + "|")]:
            for kind, frame in (("int8", oof8), ("float", oof_float)):
                sc = frame[col].to_numpy()
                rows.append(dict(model=col, arithmetic=kind, roc_auc=roc_auc_score(y, sc),
                                 average_precision=average_precision_score(y, sc),
                                 folder24_mean_score=float(frame.loc[frame.folder == "folder_24", col].mean()))
                            | crossfit(y, sc, folds))
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--tag", default="", help="read/write outputs/esp32-tflm/full-<tag>/")
    ap.add_argument("--metrics-only", action="store_true",
                    help="recompute cross-fitted metrics from saved oof_int8.csv/oof_float.csv (no conversion)")
    a = ap.parse_args()
    root = run_root(a.smoke, a.tag)
    df, groups = dev_frame(a.smoke)
    y, n = df.label.to_numpy(), len(df)
    info = root / "train_info.json"
    info = json.loads(info.read_text()) if info.exists() else {}
    if info.get("fold_of_recording"):  # non-default folds (e.g. leave-one-recorder-out) saved by training
        fold_of = np.array(info["fold_of_recording"])
        folds = [(np.flatnonzero(fold_of != k), np.flatnonzero(fold_of == k)) for k in range(fold_of.max() + 1)]
    else:
        folds = list(GroupKFold(5).split(y, y, groups))
    oof_float = pd.read_csv(root / "oof_float.csv")
    assert list(oof_float.path) == list(df.path)
    if a.metrics_only:
        oof8 = pd.read_csv(root / "oof_int8.csv")
        assert list(oof8.path) == list(df.path)
        report(root, metric_rows(oof8, oof_float, y, folds))
        return
    import tensorflow as tf

    tf.get_logger().setLevel("ERROR")
    seeds = sorted({int(c.split("seed")[1]) for c in oof_float.columns if "|seed" in c})
    max_band, gain_norm, min_band = info.get("max_band", 64), info.get("gain_norm", False), info.get("min_band", 0)
    oof8, device = oof_float[["path", "folder", "label"]].copy(), {}
    for name, cfg in CANDIDATES.items():
        if f"{name}|seed{seeds[0]}" not in oof_float:
            continue
        X, rid = units(name, df, a.smoke, max_band, gain_norm, min_band)
        for s in seeds:
            float_scores, int8_scores = np.zeros(len(X)), np.zeros(len(X))
            for k, (tr, te) in enumerate(folds):
                w = dict(np.load(root / name / f"seed{s}_fold{k}.npz"))
                mu, sd = float(w.pop("__mu")), float(w.pop("__sd"))
                model = keras_model(cfg["spec"], cfg["input"], w, mu, sd)
                tu, eu = np.isin(rid, tr), np.isin(rid, te)
                float_scores[eu] = model.predict(X[eu][..., None], batch_size=512, verbose=0).ravel()
                rep_idx = np.random.default_rng(k).choice(np.flatnonzero(tu), min(300, tu.sum()), replace=False)
                blob = to_int8(model, X[rep_idx])
                int8_scores[eu] = run_int8(blob, X[eu])
                if s == seeds[0] and k == 0:
                    ops, arena = inspect(blob)
                    out = root / name
                    (out / "model_int8.tflite").write_bytes(blob)
                    (out / "model_data.cc").write_text(c_array(blob, "g_model"))
                    it = interpreter(blob)
                    si, zi = it.get_input_details()[0]["quantization"]
                    fixture = np.clip(np.round(X[eu][0] / si + zi), -128, 127).astype(np.int8)
                    np.save(out / "fixture_input_int8.npy", fixture)
                    device[name] = dict(int8_tflite_bytes=len(blob), ops=ops,
                                        unsupported_ops=sorted(set(ops) - TFLM_OPS),
                                        arena_lower_bound_bytes=int(arena), input_scale=float(si),
                                        input_zero_point=int(zi), fixture_expected_output=float(int8_scores[eu][0]))
            rec_float = np.bincount(rid, float_scores, n) / np.bincount(rid, minlength=n)
            parity = float(np.abs(rec_float - oof_float[f"{name}|seed{s}"]).max())
            assert parity < 2e-3, f"Keras/PyTorch float mismatch {parity} for {name} seed{s}"
            oof8[f"{name}|seed{s}"] = np.bincount(rid, int8_scores, n) / np.bincount(rid, minlength=n)
            if cfg["unit"] == "window":  # on-device alternative: mean of the top 3 of each 10 windows
                oof8[f"{name}@top3of10|seed{s}"] = top_k_decisions(int8_scores, rid, n)
                oof_float[f"{name}@top3of10|seed{s}"] = top_k_decisions(float_scores, rid, n)
            print(f"{name} seed{s}: float parity {parity:.1e}; int8 AUC "
                  f"{roc_auc_score(y, oof8[f'{name}|seed{s}']):.3f}", flush=True)
    oof8.to_csv(root / "oof_int8.csv", index=False)
    oof_float.to_csv(root / "oof_float.csv", index=False)  # adds the float top-k columns
    (root / "device_report.json").write_text(json.dumps(device, indent=1))
    print(json.dumps(device, indent=1))
    report(root, metric_rows(oof8, oof_float, y, folds))


def top_k_decisions(window_scores, rid, n, group=10, k=3):
    """Recording score as the device would form it: split each recording's consecutive 1 s windows
    into 10-window (10 s) decisions, score each as the mean of its top 3 windows (top 30% for a
    shorter final group), and average the decisions."""
    out = np.zeros(n)
    bounds = np.r_[0, np.flatnonzero(np.diff(rid)) + 1, len(rid)]
    for a, b in zip(bounds[:-1], bounds[1:]):
        v = window_scores[a:b]
        decisions = []
        for start in range(0, len(v), group):
            g = np.sort(v[start:start + group])[::-1]
            decisions.append(g[:max(1, round(k * len(g) / group))].mean())
        out[rid[a]] = np.mean(decisions)
    return out


def report(root, res):
    res.to_csv(root / "results.csv", index=False)
    pd.set_option("display.width", 250)
    show = ["model", "arithmetic", "roc_auc"] + [f"{r}_{m}" for r in RULES for m in ("recall", "precision", "fpr")]
    print(res[show].round(3).to_string(index=False))


if __name__ == "__main__":
    main()
