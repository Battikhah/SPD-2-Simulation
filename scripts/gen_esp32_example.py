"""Fill firmware/esp32_stream1s/main/generated/ (git-ignored) for the ESP-IDF example.

Run in the TensorFlow venv after esp32_export.py and logmel_parity_fixtures.py:
  outputs/tf-venv/Scripts/python.exe scripts/gen_esp32_example.py
Writes model_data.cc/.h (by default the stream1s_w8 seed0/fold0 int8 model; --model picks another
model_int8.tflite, e.g. outputs/esp32-tflm/full-stream1s_w8_d4-pb2.0-lorO/stream1s_w8_d4/model_int8.tflite)
and fixture.h: one real development 1 s window (int16 PCM), its expected int8 model input checksum, and
the expected int8 output from the host TFLite reference-kernel interpreter. If the model's input
quantisation differs from the fixture file's, the stored float log-mel is requantised the way
logmel_quantize() does on the device (float32 divide and add, round half to even).
"""

import argparse
import hashlib
import struct
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from esp32_export import interpreter  # noqa: E402

MODEL = Path("outputs/esp32-tflm/full/stream1s_w8/model_int8.tflite")
FIXTURES = Path("outputs/logmel-parity/fixtures.bin")
OUT = Path("firmware/esp32_stream1s/main/generated")
COUNT = 59 * 64


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", type=Path, default=MODEL)
    blob = ap.parse_args().model.read_bytes()
    raw = FIXTURES.read_bytes()
    assert raw[:4] == b"LMEL"
    _, scale, zp = struct.unpack("<ifi", raw[4:16])
    off = 16
    pcm = np.frombuffer(raw, "<i2", 8000, off)
    q_in = np.frombuffer(raw, np.int8, COUNT, off + 16000 + 4 * COUNT)
    it = interpreter(blob)
    it.allocate_tensors()
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    m_scale, m_zp = i["quantization"]
    if not (np.isclose(m_scale, scale) and m_zp == zp):
        logmel = np.frombuffer(raw, "<f4", COUNT, off + 16000)
        q = np.round(logmel / np.float32(m_scale) + np.float32(m_zp))
        q_in = np.clip(q, -128, 127).astype(np.int8)
    it.set_tensor(i["index"], q_in.reshape(1, 59, 64, 1))
    it.invoke()
    out_q = int(it.get_tensor(o["index"]).ravel()[0])
    out_scale, out_zp = o["quantization"]
    OUT.mkdir(parents=True, exist_ok=True)
    body = ",".join(f"0x{b:02x}" for b in blob)
    (OUT / "model_data.cc").write_text(
        "// Generated by scripts/gen_esp32_example.py; do not edit.\n#include \"model_data.h\"\n"
        f"alignas(16) const unsigned char g_model[] = {{{body}}};\nconst unsigned int g_model_len = {len(blob)};\n")
    (OUT / "model_data.h").write_text(
        "#pragma once\nextern const unsigned char g_model[];\nextern const unsigned int g_model_len;\n"
        f"static constexpr char kModelHash[] = \"{hashlib.sha256(blob).hexdigest()}\";\n")
    pcm_rows = ",\n".join(",".join(map(str, pcm[r:r + 20])) for r in range(0, 8000, 20))
    (OUT / "fixture.h").write_text(
        "// Generated by scripts/gen_esp32_example.py; one real development 1 s window (PCM_16).\n#pragma once\n"
        "#include <cstdint>\n"
        f"static const int16_t kFixturePcm[8000] = {{\n{pcm_rows}}};\n"
        f"static constexpr int kExpectedInputSum = {int(q_in.astype(np.int64).sum())};\n"
        f"static constexpr int kExpectedOutput = {out_q};  // host TFLite reference kernels\n"
        f"static constexpr float kOutputScale = {out_scale!r}f;\nstatic constexpr int kOutputZeroPoint = {out_zp};\n")
    p = (out_q - out_zp) * out_scale
    print(f"wrote {OUT}: model {len(blob)} B, fixture expected int8 output {out_q} (probability {p:.4f})")


if __name__ == "__main__":
    main()
