"""Generate firmware/logmel/logmel_tables.h from the exact Python training feature code.

The periodic Hann window (np.hanning(513)[:-1]) and the 64-band HTK mel matrix are taken from
`grouped_cv_campaign.py` (WINDOW, MEL64), so the C coefficients equal the training coefficients
rounded once to float32. The mel matrix is stored sparsely (start bin, length, weights per band).
FFT twiddles are cos/sin(2*pi*k/512) computed in float64 and rounded to float32.
"""

import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from grouped_cv_campaign import MEL64, WINDOW  # noqa: E402

OUT = Path("firmware/logmel/logmel_tables.h")


def c_float(v):
    """9 significant digits round-trip float32 exactly; keep a '.' or exponent so 'f' is legal C."""
    s = f"{np.float32(v):.9g}"
    return (s if any(ch in s for ch in ".en") else s + ".0") + "f"


def floats(values, per_line=6):
    items = [c_float(v) for v in values]
    return ",\n    ".join(", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line))


def main():
    assert WINDOW.shape == (512,) and MEL64.shape == (64, 257)
    starts, lengths, offsets, weights = [], [], [], []
    for band in MEL64:
        nz = np.flatnonzero(band > 0)
        start, stop = int(nz[0]), int(nz[-1]) + 1
        assert np.all(band[:start] == 0) and np.all(band[stop:] == 0)
        starts.append(start)
        lengths.append(stop - start)
        offsets.append(len(weights))
        weights.extend(band[start:stop])
    k = np.arange(256)
    text = f"""/* Generated by scripts/gen_logmel_tables.py -- do not edit.
 * Source: WINDOW and MEL64 in scripts/grouped_cv_campaign.py (training feature contract).
 * Window: periodic Hann, np.hanning(513)[:-1]. Mel: 64 HTK bands over 257 rFFT bins at 8 kHz.
 */
#ifndef LOGMEL_TABLES_H
#define LOGMEL_TABLES_H
#include <stdint.h>

#define LOGMEL_MEL_WEIGHTS {len(weights)}

static const float LOGMEL_WINDOW[512] = {{
    {floats(WINDOW)}
}};

/* Twiddles for the 512-point complex FFT: W^k = cos(2*pi*k/512) - i*sin(2*pi*k/512), k < 256. */
static const float LOGMEL_COS[256] = {{
    {floats(np.cos(2 * np.pi * k / 512))}
}};
static const float LOGMEL_SIN[256] = {{
    {floats(np.sin(2 * np.pi * k / 512))}
}};

static const uint16_t LOGMEL_BAND_START[64] = {{{", ".join(map(str, starts))}}};
static const uint16_t LOGMEL_BAND_LEN[64] = {{{", ".join(map(str, lengths))}}};
static const uint16_t LOGMEL_BAND_OFFSET[64] = {{{", ".join(map(str, offsets))}}};
static const float LOGMEL_MEL_W[LOGMEL_MEL_WEIGHTS] = {{
    {floats(weights)}
}};

#endif
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, newline="\n")
    print(f"wrote {OUT}: {len(weights)} mel weights, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
