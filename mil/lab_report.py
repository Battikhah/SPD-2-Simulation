"""Lab-data experiment (writes mil/LAB_RESULTS.md): L-* runs with and without lab recordings in training.

One fixed tree-grouped split (no CV): test = healthy folders 8 and 24 (both share a recorder with infested trees)
and infested folders 5, 11, 19+23, 28; lab pseudo-clips are training only. Per-window metrics are unweighted
(each window of K recordings counts once), threshold 0.5, 95% tree-cluster bootstrap intervals; plus the mean
score per held-out folder. Development data only; the sealed groups were never loaded.

    .venv/Scripts/python.exe mil/lab_report.py
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
from skip_report import KEYS, boot, unweighted  # noqa: E402

OUT = C.MIL / "LAB_RESULTS.md"
PAIRS = [("L-AST-lab-K12", "L-AST-nolab-K12", "frozen AST (pretrained, log-mel based)"),
         ("L-cnn-lab-K12", "L-cnn-nolab-K12", "custom log-mel CNN"),
         ("L-mfcc30-lab-K12", "L-mfcc30-nolab-K12", "custom MFCC 13x30 CNN")]


def main():
    rows, folders = [], []
    for lab, nolab, short in PAIRS:
        for run, uses in ((lab, "yes"), (nolab, "no")):
            f = C.EXP / run / "seed42" / "oof_predictions.csv"
            if not f.exists():
                continue
            cfg = json.loads((C.EXP / run / "seed42" / "fold0" / "config.json").read_text())
            p = pd.read_csv(f)
            for st in ("K", "skip", "1"):
                d = p[p.stride.astype(str) == st]
                m, ci = unweighted(d), boot(d)
                rows.append(dict(run=run, short=short, lab=uses, approach=cfg["approach"], stride=st,
                                 n=f"{int((d.label == 0).sum())} / {int((d.label == 1).sum())}",
                                 **{k: m[k] for k in KEYS}, **{f"{k}_ci": ci[k] for k in KEYS},
                                 cm=f"{m['tp']:.0f} / {m['fn']:.0f} / {m['fp']:.0f} / {m['tn']:.0f}"))
            k = p[p.stride.astype(str) == "K"]
            for (fo, lab_), d in k.groupby(["folder", "label"]):
                folders.append(dict(run=run, folder=fo, label="infested" if lab_ else "healthy", mean=d.prob.mean(),
                                    flagged=(d.prob > 0.5).mean()))
    if not rows:
        print("no L-* results yet")
        return
    d = pd.DataFrame(rows)
    lines = ["# Lab-data experiment: per-window results (unweighted)", "",
             "Generated by `mil/lab_report.py`. **One fixed split, no cross-validation, one seed:** test = healthy "
             "folders 8 and 24 (the two healthy trees every earlier model flagged; both share a recorder with infested "
             "trees) and infested folders 5, 11, 19+23, 28. Training = the other 15 trees (healthy folders 7, 9, 25), "
             "plus, for the *lab* runs, 1,450 lab pseudo-clips (483 clean / 967 infested; each two 10 s lab clips "
             "joined into 20 s), never evaluated. All runs: skip-window training, K = 12, 115,200 training bags, gated "
             "attention + linear classifier. Each window of 12 recordings counts once; threshold 0.5; 95% tree-cluster "
             "bootstrap intervals (only 2 healthy test trees, so intervals are wide). Development data only; the "
             "sealed groups were never loaded.", "",
             "No pretrained MFCC encoder exists for this input (pretrained audio encoders take log-mel or waveform), so "
             "the MFCC model is a custom CNN only.", ""]
    for st, title in (("K", "Non-overlapping windows (stride K)"), ("skip", "Skip windows (100 per test folder)"),
                      ("1", "Overlapping windows (stride 1)")):
        s = d[d.stride == st]
        lines += [f"## {title}", "",
                  "| Run | Encoder | Lab data | Windows (healthy / infested) | ROC-AUC [95% CI] | Bal. acc. [95% CI] | "
                  "Recall | Specificity | Precision | F1 | TP / FN / FP / TN |",
                  "| --- | --- | --- | --- | --- | --- | ---: | ---: | ---: | ---: | --- |"]
        for r in s.itertuples():
            def ci(k, r=r):
                lo, hi = getattr(r, k + "_ci")
                return f"{getattr(r, k):.3f} [{lo:.2f}, {hi:.2f}]"
            lines.append(f"| {r.run} | **{r.short}** | {r.lab} | {r.n} | {ci('roc_auc')} | {ci('balanced_accuracy')} | "
                         f"{r.recall:.3f} | {r.specificity:.3f} | {r.precision:.3f} | {r.f1:.3f} | {r.cm} |")
        lines.append("")
    f = pd.DataFrame(folders)
    piv = f.pivot_table(index=["folder", "label"], columns="run", values="mean").round(3)
    piv = piv.reindex(sorted(piv.index, key=lambda t: (t[1], int(t[0][7:]))))
    lines += ["## Mean score per test folder (non-overlapping windows)", "",
              "| Folder | Label | " + " | ".join(piv.columns) + " |",
              "| --- | --- | " + " | ".join("---:" for _ in piv.columns) + " |"]
    for (fo, lab_), r in piv.iterrows():
        lines.append(f"| {fo[7:]} | {lab_} | " + " | ".join(f"{v:.3f}" for v in r) + " |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
