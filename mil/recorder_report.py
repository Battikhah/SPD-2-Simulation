"""Within-recorder evaluation (writes mil/RECORDER_RESULTS.md).

Headline metric: within-recorder ROC-AUC. Only three development recorders recorded both classes (2538:
healthy folder 24 vs 11 infested folders; 7260: healthy 8 vs 3; 8391: healthy 25 vs 7). Comparing windows of
the same recorder, scored by the same model, removes the device shortcut. AUC is tree-weighted within the
recorder (each tree's windows on that recorder sum to 1); the mean over the three recorders is reported per
seed, then mean and spread over seeds.

R-* runs use tree-safe leave-one-recorder-out folds (the model never heard the test recorder and never saw any
folder of a test tree). For contrast, the same metric is computed on the earlier tree-fold runs (B0, E-AST-lin,
A-win-K12), whose models did train on other folders of the same recorder.

    .venv/Scripts/python.exe mil/recorder_report.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import experiments as X  # noqa: E402
import metrics as M  # noqa: E402

OUT = C.MIL / "RECORDER_RESULTS.md"
BOTH = ("2538", "7260", "8391")
HEALTHY = {"2538": "folder_24", "7260": "folder_8", "8391": "folder_25"}
RUNS = [("R-B0", "B0"), ("R-AST-lin", "E-AST-lin"), ("R-Awin-K12", "A-win-K12")]


def within(pred, f2r):
    p = pred[pred.stride.astype(str) == "1"].copy()
    p["rec"] = p.folder.map(f2r)
    out = {}
    for r in BOTH:
        d = p[p.rec == r]
        tree = d.tree_group.to_numpy()
        w = M.window_weights(tree, d.label.to_numpy(), "tree")
        m = M.binary_metrics(d.label.to_numpy(), d.prob.to_numpy(), w)
        h = d[d.folder == HEALTHY[r]].prob
        out[r] = dict(auc=m["roc_auc"], auc_unweighted=M.weighted_auc(d.label.to_numpy(), d.prob.to_numpy(),
                                                                      np.ones(len(d))),
                      healthy_mean=float(h.mean()), healthy_flagged=float((h > 0.5).mean()),
                      infested_mean=float(d[d.label == 1].groupby("tree_group").prob.mean().mean()),
                      recall=m["recall"], specificity=m["specificity"])
    out["mean"] = dict(auc=float(np.mean([out[r]["auc"] for r in BOTH])),
                       balanced=float(np.mean([np.nanmean([out[r]["recall"], out[r]["specificity"]]) for r in BOTH])))
    return out


def seeds_of(name):
    return sorted(int(sd.name[4:]) for sd in (C.EXP / name).glob("seed*") if (sd / "oof_predictions.csv").exists())


def main():
    _, f2r = C.recorder_folds()
    lines = ["# Within-recorder results", "",
             "Generated by `mil/recorder_report.py`. Development data only; the sealed groups were never loaded.", "",
             "**Why this test:** every earlier model flags healthy folders 8 and 24, which share recorders with infested "
             "trees. Within one recorder the device is the same, so only a difference in the trees can separate healthy "
             "from infested. Three recorders recorded both classes:", "",
             "| Recorder | Healthy folder | Infested folders |", "| --- | --- | --- |"]
    for r in BOTH:
        inf = sorted({f for f, rr in f2r.items() if rr == r} - {HEALTHY[r]}, key=lambda x: int(x[7:]))
        lines.append(f"| {r} | {HEALTHY[r][7:]} | {', '.join(f[7:] for f in inf)} |")
    lines += ["", "**R-\\* runs:** tree-safe leave-one-recorder-out (6 folds, one per development recorder). The test "
              "recorder is never heard in training, and a tree group with any folder on it is removed from training.",
              "Within-recorder AUC is tree-weighted within each recorder; 0.5 is chance. Spread is over seeds.", "",
              "## Summary", "",
              "| Run | Architecture / approach | Folds | Seeds | Mean within-recorder AUC | AUC 2538 (f24) | AUC 7260 (f8) | "
              "AUC 8391 (f25) | Healthy windows flagged (f24 / f8 / f25) | Pooled tree-weighted AUC | Pooled tree-weighted "
              "bal. acc. |", "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: |"]
    detail = []
    for rname, tname in RUNS:
        for name, folds in ((rname, "leave-one-recorder-out"), (tname, "tree folds (reference)")):
            seeds = seeds_of(name)
            if not seeds:
                continue
            res, summ = [], []
            for s in seeds:
                sd = C.EXP / name / f"seed{s}"
                res.append(within(pd.read_csv(sd / "oof_predictions.csv"), f2r))
                summ.append(pd.read_csv(sd / "summary.csv", index_col=0))
            appr = json.loads((C.EXP / name / f"seed{seeds[0]}" / "fold0" / "config.json").read_text()).get("approach") \
                or X.approach(name)

            def ms(vals):
                v = np.array(vals, float)
                return f"{v.mean():.3f}" + (f" ± {v.std(ddof=1):.3f}" if len(v) > 1 else "")

            flag = " / ".join(ms([r_[k]["healthy_flagged"] for r_ in res]) for k in BOTH)
            lines.append(f"| {name} | {appr} | {folds} | {len(seeds)} | **{ms([r_['mean']['auc'] for r_ in res])}** | "
                         + " | ".join(ms([r_[k]["auc"] for r_ in res]) for k in BOTH) + f" | {flag} | "
                         f"{ms([s_.loc[M.PRIMARY[0]].value for s_ in summ])} | {ms([s_.loc[M.PRIMARY[1]].value for s_ in summ])} |")
            for s, r_ in zip(seeds, res):
                for k in BOTH:
                    detail.append(dict(run=name, seed=s, recorder=k, **{q: round(v, 3) for q, v in r_[k].items()}))
    lines += ["", "## Per recorder and seed", "",
              "`healthy_mean` / `infested_mean`: mean window score of the healthy folder and of the infested trees "
              "(tree-averaged) on that recorder.", ""]
    if detail:
        d = pd.DataFrame(detail)
        cols = ["run", "seed", "recorder", "auc", "auc_unweighted", "healthy_mean", "infested_mean", "healthy_flagged",
                "recall", "specificity"]
        lines += ["| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
        lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in d[cols].itertuples(index=False)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
