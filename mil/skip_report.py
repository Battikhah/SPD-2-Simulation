"""Per-window, unweighted results for the skip-window campaign (writes mil/SKIP_RESULTS.md).

Every window (one bag of K recordings fed to the model) counts once. Three kinds of held-out windows:
  stride K  non-overlapping consecutive windows (each recording used once; the fairest window count)
  stride 1  consecutive windows sliding by one recording (heavily overlapping, not independent)
  skip      random time-ordered windows within 48 h (the training-window type); 100 per held-out folder for
            XS-* runs, 20 for S-skip
Threshold 0.5; 95% intervals are tree-cluster bootstraps (1,000 draws). Development data only; the sealed groups
were never loaded.

    .venv/Scripts/python.exe mil/skip_report.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import metrics as M  # noqa: E402

OUT = C.MIL / "SKIP_RESULTS.md"
RUNS = ["XS-mfcc15", "XS-mfcc30", "XS-AST-lin", "XS-BEATs-lin", "XS-PANNs-lin", "XS-cnn", "S-skip", "B0"]
RUNS = RUNS + [r + "-K12" for r in RUNS]
KEYS = ("roc_auc", "balanced_accuracy", "recall", "specificity", "precision", "f1", "accuracy")
SHORT = {"XS-mfcc15": "MFCC 13x15 CNN", "XS-mfcc30": "MFCC 13x30 CNN", "XS-AST-lin": "frozen AST", "XS-BEATs-lin":
         "frozen BEATs", "XS-PANNs-lin": "frozen PANNs", "XS-cnn": "log-mel CNN", "S-skip": "log-mel CNN",
         "B0": "log-mel CNN"}


def unweighted(d):
    return M.binary_metrics(d.label.to_numpy(), d.prob.to_numpy(), np.ones(len(d)))


def boot(d, n=1000, seed=0):
    """Tree-cluster bootstrap of unweighted window metrics (stratified by class)."""
    rng = np.random.default_rng(seed)
    trees = d.groupby("tree_group").label.first()
    h, i = trees.index[trees == 0].to_numpy(), trees.index[trees == 1].to_numpy()
    by = {t: g for t, g in d.groupby("tree_group")}
    vals = {k: [] for k in KEYS}
    for _ in range(n):
        dd = pd.concat([by[t] for t in np.concatenate([rng.choice(h, len(h)), rng.choice(i, len(i))])])
        m = unweighted(dd)
        for k in KEYS:
            vals[k].append(m[k])
    return {k: np.nanpercentile(v, [2.5, 97.5]) for k, v in vals.items()}


def main():
    rows = []
    for run in RUNS:
        f = C.EXP / run / "seed42" / "oof_predictions.csv"
        if not f.exists():
            continue
        cfg = json.loads((C.EXP / run / "seed42" / "fold0" / "config.json").read_text())
        p = pd.read_csv(f)
        for st in ("K", "1", "skip"):
            d = p[p.stride.astype(str) == st]
            if d.empty:
                continue
            m, ci = unweighted(d), boot(d)
            rows.append(dict(run=run, arch=cfg.get("approach", run), short=SHORT[run.replace("-K12", "")], k=cfg["k"],
                             steps=cfg.get("epochs", 30) * cfg.get("steps", 64) * 2 * cfg.get("per_class", 3), skip=cfg.get("skip"), stride=st,
                             nh=int((d.label == 0).sum()), ni=int((d.label == 1).sum()),
                             **{k: m[k] for k in KEYS}, **{f"{k}_ci": ci[k] for k in KEYS},
                             tp=m["tp"], fn=m["fn"], fp=m["fp"], tn=m["tn"]))
    d = pd.DataFrame(rows)
    lines = ["# Skip-window campaign: per-window results (unweighted)", "",
             "Generated by `mil/skip_report.py`. Every window (one bag of K recordings fed to the model) counts once; "
             "threshold 0.5; 95% intervals are tree-cluster bootstraps (1,000 draws). Held-out folds of tree-grouped "
             "10-fold CV on development data only; the sealed groups were never loaded.", "",
             "**XS-\\* runs:** skip-window training (K recordings in time order from a random stretch of at most 48 h), "
             "10x the training windows of every earlier run (115,200 bags per fold vs 11,520), tree-grouped 10-fold "
             "CV, seed 42. More windows reuse the same recordings and the same 21 trees (5 healthy); they are not new "
             "data. S-skip / B0 rows are the earlier 11,520-bag runs for reference (B0 has no skip windows).", "",
             "**Architectures:** log-mel CNN = trainable 4-block CNN clip encoder on log-mel 64x626; MFCC 13xT CNN = "
             "trainable 4-conv CNN clip encoder on whole-clip MFCC (13 coefficients x T time chunks of the 20 s clip, "
             "mean-pooled); frozen AST / BEATs / PANNs = frozen AudioSet-pretrained embeddings (768 / 768 / 2048-d). "
             "Every model then uses gated-attention MIL pooling and a linear classifier. No pretrained MFCC encoder "
             "was used (none suitable exists; see the campaign notes in AGENTS.md).", ""]
    for st, title in (("K", "Non-overlapping windows (stride K)"), ("skip", "Skip windows (training-type windows)"),
                      ("1", "Overlapping windows (stride 1)")):
        s = d[d.stride == st]
        if s.empty:
            continue
        lines += [f"## {title}", "",
                  "| Run | Architecture | K | Training bags/fold | Windows (healthy / infested) | ROC-AUC [95% CI] | "
                  "Bal. acc. [95% CI] | Recall | Specificity | Precision | F1 | Accuracy | TP / FN / FP / TN |",
                  "| --- | --- | ---: | ---: | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |"]
        for r in s.itertuples():
            ci = lambda k: f"{getattr(r, k):.3f} [{getattr(r, k + '_ci')[0]:.2f}, {getattr(r, k + '_ci')[1]:.2f}]"  # noqa: E731
            lines.append(f"| {r.run} | **{r.short}**: {r.arch} | {r.k} | {r.steps:,} | {r.nh} / {r.ni} | {ci('roc_auc')} | "
                         f"{ci('balanced_accuracy')} | {r.recall:.3f} | {r.specificity:.3f} | {r.precision:.3f} | "
                         f"{r.f1:.3f} | {r.accuracy:.3f} | {r.tp:.0f} / {r.fn:.0f} / {r.fp:.0f} / {r.tn:.0f} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
