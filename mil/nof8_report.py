"""Re-score saved out-of-fold predictions with healthy folder 8 removed from evaluation (writes
mil/NO_F8_RESULTS.md and outputs/mil/nof8_metrics.csv). No retraining: folder 8 stays in the training data of the
folds that trained on it. Window metrics (threshold 0.5) are reported unweighted (each window of K recordings once)
and tree-weighted (each tree's windows sum to 1), on non-overlapping (stride K) and overlapping (stride 1) windows;
tree-day metrics use the daily mean window score (threshold 0.5). Multi-seed runs: mean over seeds. Development data
only; the sealed groups were never loaded.

    .venv/Scripts/python.exe mil/nof8_report.py
"""

import glob
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import metrics as M  # noqa: E402

KEYS = ("roc_auc", "balanced_accuracy", "recall", "specificity", "precision", "f1", "accuracy")
EXCLUDE = "folder_8"


def scores(d, unit):
    y, s = d.label.to_numpy(), d.prob.to_numpy()
    out = {}
    for wn in ("unweighted", "tree"):
        w = M.window_weights(d.tree_group.to_numpy(), y, wn)
        m = M.binary_metrics(y, s, w)
        out.update({f"{unit}/{wn}/{k}": m[k] for k in KEYS})
    return out


def daily(p):
    p = p[p.stride.astype(str) == "1"].copy()
    t = pd.to_datetime(p.start_time) + (pd.to_datetime(p.end_time) - pd.to_datetime(p.start_time)) / 2
    p["day"] = t.dt.date
    return p.groupby(["tree_group", "folder", "day", "label"]).prob.mean().reset_index()


def main():
    rows = []
    for f in sorted(glob.glob(str(C.EXP / "*" / "seed*" / "oof_predictions.csv"))):
        f = Path(f)
        run, seed = f.parent.parent.name, int(f.parent.name[4:])
        cfg = json.loads((f.parent / "fold0" / "config.json").read_text())
        p = pd.read_csv(f)
        for excl in (False, True):
            q = p[p.folder != EXCLUDE] if excl else p
            row = dict(run=run, seed=seed, k=cfg["k"], approach=cfg.get("approach", run),
                       grouping=cfg.get("grouping", "tree"), without_f8=excl)
            for st, unit in (("K", "winK"), ("1", "win1")):
                d = q[q.stride.astype(str) == st]
                row.update(scores(d, unit))
                row[f"{unit}/n"] = f"{int((d.label == 0).sum())}/{int((d.label == 1).sum())}"
            dd = daily(q)
            row.update(scores(dd, "day"))
            row["day/n"] = f"{int((dd.label == 0).sum())}/{int((dd.label == 1).sum())}"
            rows.append(row)
    d = pd.DataFrame(rows)
    d.to_csv(C.OUT / "nof8_metrics.csv", index=False)
    num = [c for c in d.columns if "/" in c and not c.endswith("/n")]
    g = d.groupby(["run", "without_f8"], sort=False)
    mean = g[num].mean()
    first = g[["k", "approach", "grouping"] + [c for c in d.columns if c.endswith("/n")]].first()
    seeds = g.seed.nunique()
    lines = ["# Results without healthy folder 8", "",
             "Generated by `mil/nof8_report.py`. Saved out-of-fold predictions re-scored with folder 8 (fig tree, "
             "recorded on a rainy day; flagged by every model) removed from evaluation. **No retraining**: folder 8 "
             "is still in the training data of folds that used it. Threshold 0.5. *Unweighted* = each window (or "
             "tree-day) counts once; *tree-weighted* = each tree counts equally. Mean over seeds for multi-seed runs. "
             "L-* runs use one fixed split (test: healthy 8 and 24, infested 5, 11, 19+23, 28), so without folder 8 "
             "their only healthy test tree is folder 24. Development data only; sealed groups never loaded.", ""]
    for unit, title in (("winK", "Non-overlapping windows (stride K)"), ("day", "Tree-day decisions (daily mean score)"),
                        ("win1", "Overlapping windows (stride 1)")):
        for wn, wt in (("unweighted", "unweighted"), ("tree", "tree-weighted")):
            lines += [f"## {title}, {wt}, without folder 8", "",
                      "| Run | Architecture / approach | K | Folds | Seeds | Units (healthy/infested) | AUC | Bal. acc. | "
                      "Recall | Specificity | Precision | F1 | Accuracy | AUC with folder 8 |",
                      "| --- | --- | ---: | --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
            for run in mean.index.get_level_values(0).unique():
                a, b, fi = mean.loc[(run, True)], mean.loc[(run, False)], first.loc[(run, True)]
                v = [f"{a[f'{unit}/{wn}/{k}']:.3f}" for k in KEYS]
                lines.append(f"| {run} | {fi.approach} | {fi.k} | {fi.grouping} | {seeds.loc[(run, True)]} | "
                             f"{fi[f'{unit}/n']} | " + " | ".join(v) + f" | {b[f'{unit}/{wn}/roc_auc']:.3f} |")
            lines.append("")
    (C.MIL / "NO_F8_RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print(C.MIL / "NO_F8_RESULTS.md")


if __name__ == "__main__":
    main()
