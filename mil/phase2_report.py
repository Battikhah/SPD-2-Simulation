"""Phase-2 results (writes mil/PHASE2_RESULTS.md): unweighted per-window metrics and within-recorder AUC per
run and seed, the 3-seed summary, and the decision rule fixed in mil/PHASE2_PLAN.md (vs P-base at the same K).

All P-* and R-* runs use tree-safe leave-one-recorder-out folds. Development data only; sealed groups never loaded.

    .venv/Scripts/python.exe mil/phase2_report.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common as C  # noqa: E402
import metrics as M  # noqa: E402
from recorder_report import BOTH, within  # noqa: E402

OUT = C.MIL / "PHASE2_RESULTS.md"
KEYS = ("roc_auc", "balanced_accuracy", "recall", "specificity", "precision", "f1")


def runs():
    names = sorted({p.parent.parent.name for p in C.EXP.glob("P-*/seed*/oof_predictions.csv")})
    refs = [n for n in ("R-B0", "R-Awin-K12", "R-AST-lin") if (C.EXP / n).exists()]
    return names + refs


def per_seed(name, f2r):
    rows = []
    for f in sorted(C.EXP.glob(f"{name}/seed*/oof_predictions.csv")):
        cfg = json.loads((f.parent / "fold0" / "config.json").read_text())
        p = pd.read_csv(f)
        row = dict(run=name, seed=int(f.parent.name[4:]), k=cfg["k"], approach=cfg.get("approach", name),
                   bags=cfg["epochs"] * cfg["steps"] * 2 * cfg["per_class"], skip=bool(cfg.get("skip")))
        for st in ("K", "skip", "1"):
            d = p[p.stride.astype(str) == st]
            if d.empty:
                continue
            m = M.binary_metrics(d.label.to_numpy(), d.prob.to_numpy(), np.ones(len(d)))
            for k in KEYS:
                row[f"{st}/{k}"] = m[k]
            row[f"{st}/n"] = f"{int((d.label == 0).sum())} / {int((d.label == 1).sum())}"
        w = within(p, f2r)
        row["within_auc"] = w["mean"]["auc"]
        for r in BOTH:
            row[f"auc_{r}"] = w[r]["auc"]
        rows.append(row)
    return rows


def decide(s, base):
    """PHASE2_PLAN decision rule on per-seed rows s vs base (same K)."""
    a, b = s["K/roc_auc"].to_numpy(), base["K/roc_auc"].to_numpy()
    if len(a) < 2 or len(b) < 2:
        return "n/a (needs 2+ seeds of both)"
    sd = max(a.std(ddof=1), b.std(ddof=1))
    gain = a.mean() - b.mean()
    ok = (gain > 2 * sd) and (s.within_auc.mean() >= base.within_auc.mean()) and ((a > b.mean()).sum() >= 2)
    return f"{'**better**' if ok else 'not better'} (gain {gain:+.3f}, 2 x seed SD {2 * sd:.3f})"


def fmt(v, sd=None):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return "n/a"
    return f"{v:.3f}" if sd is None or np.isnan(sd) else f"{v:.3f} ± {sd:.3f}"


def main():
    _, f2r = C.recorder_folds()
    rows = sum((per_seed(n, f2r) for n in runs()), [])
    if not rows:
        print("no phase-2 results yet")
        return
    d = pd.DataFrame(rows)
    d.to_csv(C.OUT / "phase2_per_seed.csv", index=False)
    lines = ["# Phase 2 results: device-robust MIL models", "",
             "Generated by `mil/phase2_report.py`. Plan and decision rule (fixed before results): `mil/PHASE2_PLAN.md`. "
             "Every run uses tree-safe leave-one-recorder-out folds (the test recorder is never heard in training). "
             "Per-window metrics are **unweighted** (each window of K recordings counts once), threshold 0.5. "
             "Within-recorder AUC is tree-weighted inside each of the 3 recorders with both classes (0.5 = chance). "
             "Mean ± SD over seeds. Development data only; the sealed groups were never loaded.", "",
             "| Run | Architecture / approach | K | Seeds | Bags/fold | Stride-K AUC | Stride-K bal. acc. | Stride-K recall | "
             "Stride-K spec. | Skip-window AUC | Stride-1 AUC | Within-recorder AUC (mean) | 2538 / 7260 / 8391 | "
             "Decision vs P-base |",
             "| --- | --- | ---: | ---: | ---: | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for (name, k), s in d.groupby(["run", "k"], sort=False):
        base = d[(d.run == "P-base" + ("-K12" if k == 12 else "")) & (d.k == k)]
        dec = "reference" if name.startswith("P-base") else (decide(s, base) if name.startswith("P-") else "reference run")

        def ms(col):
            if col not in s or s[col].isna().all():
                return "n/a"
            return fmt(s[col].mean(), s[col].std(ddof=1) if len(s) > 1 else np.nan)

        rec = " / ".join(f"{s[f'auc_{r}'].mean():.2f}" for r in BOTH)
        lines.append(f"| {name} | {s.approach.iloc[0]} | {k} | {len(s)} | {s.bags.iloc[0]:,} | {ms('K/roc_auc')} | "
                     f"{ms('K/balanced_accuracy')} | {ms('K/recall')} | {ms('K/specificity')} | {ms('skip/roc_auc')} | "
                     f"{ms('1/roc_auc')} | {ms('within_auc')} | {rec} | {dec} |")
    lines += ["", "Per-seed values: `outputs/mil/phase2_per_seed.csv`.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
